#!/usr/bin/env python3
"""
assemble_detailed_anime_video.py
Assembles high-detail anime illustrations generated by AI into an epic kawaii anime battle trailer.
Features:
- Sub-pixel Ken Burns camera pan & zoom
- Sakura petal physics & floating light bokeh
- Electric crackling aura effects
- Dynamic camera shakes synchronized with J-Rock chiptune beats
- Anime typography with glowing outlines & Japanese kanji
- Seamless crossfades and flash cuts
- Direct pipe to FFmpeg H.264 + AAC
"""

import os
import sys
import math
import random
import subprocess
import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageFilter

W, H = 720, 540
FPS = 24
TOTAL_FRAMES = 360  # 15.0 seconds
AUDIO_PATH = "/home/iuliiadabizha/natalies-finger/anime_intro_audio.wav"
OUTPUT_PATH = "/home/iuliiadabizha/natalies-finger/intro.mp4"
ART_DIR = "/home/iuliiadabizha/natalies-finger/anime_art"

# Try loading TrueType fonts, fallback to default
def get_font(size):
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
        "/usr/share/fonts/truetype/freefont/FreeSansBold.ttf",
        "/usr/share/fonts/truetype/ubuntu/Ubuntu-B.ttf"
    ]
    for c in candidates:
        if os.path.exists(c):
            try:
                return ImageFont.truetype(c, size)
            except Exception:
                pass
    return ImageFont.load_default()

font_huge = get_font(38)
font_large = get_font(28)
font_mid = get_font(18)
font_small = get_font(13)

def load_and_fit_image(path):
    if not os.path.exists(path):
        # Fallback placeholder if image not yet found
        img = Image.new("RGB", (W, H), (20, 10, 35))
        draw = ImageDraw.Draw(img)
        draw.text((W//2 - 80, H//2), "Generating...", fill=(255, 255, 255), font=font_large)
        return img
    img = Image.open(path).convert("RGB")
    # Scale to cover W, H while maintaining aspect ratio
    iw, ih = img.size
    scale = max(W / iw, H / ih)
    nw, nh = int(iw * scale), int(ih * scale)
    img = img.resize((nw, nh), Image.Resampling.LANCZOS)
    # Center crop
    left = (nw - W) // 2
    top = (nh - H) // 2
    return img.crop((left, top, left + W, top + H))

def apply_ken_burns(img, z_start, z_end, pan_x_start, pan_x_end, pan_y_start, pan_y_end, progress):
    zoom = z_start + (z_end - z_start) * progress
    px = pan_x_start + (pan_x_end - pan_x_start) * progress
    py = pan_y_start + (pan_y_end - pan_y_start) * progress

    cw = int(W / zoom)
    ch = int(H / zoom)

    cx = int(W / 2 + px)
    cy = int(H / 2 + py)

    x1 = max(0, min(W - cw, cx - cw // 2))
    y1 = max(0, min(H - ch, cy - ch // 2))
    x2 = x1 + cw
    y2 = y1 + ch

    crop = img.crop((x1, y1, x2, y2))
    return crop.resize((W, H), Image.Resampling.BILINEAR)

def draw_text_bordered(draw, pos, text, font, fill=(255, 255, 255), border=(0, 0, 0), bw=3):
    x, y = pos
    for dx in range(-bw, bw + 1):
        for dy in range(-bw, bw + 1):
            if dx != 0 or dy != 0:
                draw.text((x + dx, y + dy), text, font=font, fill=border)
    draw.text((x, y), text, font=font, fill=fill)

def draw_centered_text(draw, y, text, font, fill=(255, 255, 255), border=(0, 0, 0), bw=3):
    bbox = draw.textbbox((0, 0), text, font=font)
    tw = bbox[2] - bbox[0]
    x = (W - tw) // 2
    draw_text_bordered(draw, (x, y), text, font, fill, border, bw)

# Initialize Sakura Petals
random.seed(42)
sakura_petals = [
    {
        'x': random.uniform(0, W),
        'y': random.uniform(-100, H),
        'vx': random.uniform(1.0, 3.0),
        'vy': random.uniform(1.2, 2.8),
        'size': random.uniform(6, 12),
        'angle': random.uniform(0, math.pi * 2),
        'vRot': random.uniform(0.04, 0.12),
        'color': random.choice([(255, 183, 197), (255, 192, 203), (255, 218, 224), (255, 160, 180)])
    }
    for _ in range(35)
]

def update_and_draw_sakura(draw):
    for p in sakura_petals:
        p['x'] = (p['x'] + p['vx'] + math.sin(p['angle']) * 0.8) % (W + 20)
        p['y'] = (p['y'] + p['vy']) % (H + 20)
        p['angle'] += p['vRot']

        px, py, s = p['x'], p['y'], p['size']
        ang = p['angle']
        # Petal ellipse points
        cos_a = math.cos(ang)
        sin_a = math.sin(ang)
        dx1, dy1 = cos_a * s, sin_a * (s * 0.5)
        dx2, dy2 = -sin_a * (s * 0.5), cos_a * s
        points = [
            (px - dx1, py - dy1),
            (px + dx2, py + dy2),
            (px + dx1, py + dy1),
            (px - dx2, py - dy2)
        ]
        draw.polygon(points, fill=p['color'])

def draw_electric_arc(draw, x1, y1, x2, y2, color=(129, 236, 236), segments=7, jitter=14):
    points = [(x1, y1)]
    for i in range(1, segments):
        t = i / segments
        bx = x1 + (x2 - x1) * t + random.uniform(-jitter, jitter)
        by = y1 + (y2 - y1) * t + random.uniform(-jitter, jitter)
        points.append((bx, by))
    points.append((x2, y2))
    for i in range(len(points) - 1):
        draw.line([points[i], points[i+1]], fill=color, width=3)
        draw.line([points[i], points[i+1]], fill=(255, 255, 255), width=1)

def main():
    print("Pre-loading AI-generated anime keyframe illustrations...")
    img_hero = load_and_fit_image(os.path.join(ART_DIR, "scene1_hero.png"))
    img_natalie = load_and_fit_image(os.path.join(ART_DIR, "scene2_natalie.png"))
    img_vs = load_and_fit_image(os.path.join(ART_DIR, "scene3_vs_clash.png"))
    img_crew = load_and_fit_image(os.path.join(ART_DIR, "scene4_crew_squad.png"))
    img_climax = load_and_fit_image(os.path.join(ART_DIR, "scene5_beam_struggle.png"))

    print(f"Setting up FFmpeg pipe -> {OUTPUT_PATH}...")
    cmd = [
        "ffmpeg", "-y",
        "-f", "rawvideo",
        "-pix_fmt", "rgb24",
        "-s", f"{W}x{H}",
        "-r", str(FPS),
        "-i", "-",  # Video from stdin
        "-i", AUDIO_PATH,  # Audio from WAV
        "-c:v", "libx264",
        "-pix_fmt", "yuv420p",
        "-crf", "18",
        "-preset", "medium",
        "-c:a", "aac",
        "-b:a", "192k",
        "-shortest",
        OUTPUT_PATH
    ]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)

    print("Rendering 360 detailed anime battle frames...")

    for f in range(TOTAL_FRAMES):
        t = f / FPS  # Current second (0.0 to 15.0)

        # --------------------------------------------------------
        # SCENE 1: HERO TROLL-KUN (0.0s - 3.0s | frames 0 - 71)
        # --------------------------------------------------------
        if f < 72:
            prog = f / 71.0
            frame_img = apply_ken_burns(img_hero, z_start=1.18, z_end=1.03,
                                        pan_x_start=-25, pan_x_end=20,
                                        pan_y_start=15, pan_y_end=-10, progress=prog)
            draw = ImageDraw.Draw(frame_img)
            update_and_draw_sakura(draw)

            # Glowing Title Card
            draw_text_bordered(draw, (45, 45), "⚡ HERO TROLL-KUN ⚡", font_large,
                               fill=(129, 236, 236), border=(0, 0, 0), bw=4)
            draw_text_bordered(draw, (48, 85), "【 トロール勇者 • TROLL HEIST 】", font_mid,
                               fill=(255, 255, 255), border=(0, 0, 0), bw=3)

            # Flash out at end of scene
            if f >= 68:
                alpha = int(((f - 67) / 4.0) * 255)
                flash = Image.new("RGBA", (W, H), (255, 255, 255, alpha))
                frame_img.paste(flash, (0, 0), flash)

        # --------------------------------------------------------
        # SCENE 2: TYRANT NATALIE (3.0s - 6.0s | frames 72 - 143)
        # --------------------------------------------------------
        elif f < 144:
            prog = (f - 72) / 71.0
            # Dramatic push-in zoom into Natalie's furious eyes
            frame_img = apply_ken_burns(img_natalie, z_start=1.02, z_end=1.28,
                                        pan_x_start=15, pan_x_end=-10,
                                        pan_y_start=20, pan_y_end=-15, progress=prog)
            draw = ImageDraw.Draw(frame_img)

            # Electric aura arcs crackling
            for _ in range(3):
                ax = random.randint(W//2 - 180, W//2 + 180)
                ay = random.randint(40, H - 40)
                draw_electric_arc(draw, ax, ay, ax + random.randint(-60, 60), ay + random.randint(-60, 60),
                                  color=(255, 71, 87), segments=5, jitter=12)

            # Beat pulse screen shake on kick beats
            if f % 12 < 3:
                shake_x = random.randint(-5, 5)
                shake_y = random.randint(-5, 5)
                frame_img = Image.fromarray(np.roll(np.roll(np.array(frame_img), shake_x, axis=1), shake_y, axis=0))
                draw = ImageDraw.Draw(frame_img)

            # Villain Title Card
            draw_text_bordered(draw, (W - 380, 45), "🔥 TYRANT NATALIE 🔥", font_large,
                               fill=(255, 71, 87), border=(0, 0, 0), bw=4)
            draw_text_bordered(draw, (W - 376, 85), "【 暴君店長 • 50YO TYRANT 】", font_mid,
                               fill=(255, 234, 167), border=(0, 0, 0), bw=3)

            # Flash out at end of scene
            if f >= 140:
                alpha = int(((f - 139) / 4.0) * 255)
                flash = Image.new("RGBA", (W, H), (255, 100, 100, alpha))
                frame_img.paste(flash, (0, 0), flash)

        # --------------------------------------------------------
        # SCENE 3: EPIC VS CLASH (6.0s - 9.0s | frames 144 - 215)
        # --------------------------------------------------------
        elif f < 216:
            prog = (f - 144) / 71.0
            frame_img = apply_ken_burns(img_vs, z_start=1.08, z_end=1.02,
                                        pan_x_start=0, pan_x_end=0,
                                        pan_y_start=10, pan_y_end=-10, progress=prog)
            draw = ImageDraw.Draw(frame_img)

            # Lightning impact flash at start of scene
            if f < 148:
                flash_alpha = int((1.0 - (f - 144) / 4.0) * 220)
                white = Image.new("RGBA", (W, H), (255, 255, 255, flash_alpha))
                frame_img.paste(white, (0, 0), white)
                draw = ImageDraw.Draw(frame_img)

            # Central lightning clash effect
            draw_electric_arc(draw, W//2 - 20, 0, W//2 + 20, H,
                              color=(255, 234, 167), segments=9, jitter=22)

            # Embers / sparks spraying from the center
            for _ in range(8):
                sx = W//2 + random.randint(-40, 40)
                sy = random.randint(80, H - 80)
                draw.rectangle([sx, sy, sx+4, sy+4], fill=(255, 215, 0))

            # VS Banner
            pulse = math.sin(prog * math.pi * 6) * 3
            draw_centered_text(draw, int(H//2 - 40 + pulse), "⚔️  V S  ⚔️", font_huge,
                               fill=(255, 215, 0), border=(192, 57, 43), bw=5)
            draw_centered_text(draw, int(H//2 + 15 + pulse), "【 宿命の対決 • SHOWDOWN 】", font_mid,
                               fill=(255, 255, 255), border=(0, 0, 0), bw=3)

            # Flash out at end of scene
            if f >= 212:
                alpha = int(((f - 211) / 4.0) * 255)
                flash = Image.new("RGBA", (W, H), (255, 255, 255, alpha))
                frame_img.paste(flash, (0, 0), flash)

        # --------------------------------------------------------
        # SCENE 4: THE 7 CREW HEROES SQUAD (9.0s - 12.0s | frames 216 - 287)
        # --------------------------------------------------------
        elif f < 288:
            prog = (f - 216) / 71.0
            # Panoramic pan across the heroic workers
            frame_img = apply_ken_burns(img_crew, z_start=1.12, z_end=1.04,
                                        pan_x_start=-35, pan_x_end=35,
                                        pan_y_start=0, pan_y_end=0, progress=prog)
            draw = ImageDraw.Draw(frame_img)

            # Floating golden stars
            for i in range(12):
                star_x = int((i * 65 + prog * 40) % W)
                star_y = int(60 + math.sin(prog * 5 + i) * 25)
                draw.rectangle([star_x, star_y, star_x+3, star_y+3], fill=(255, 234, 167))

            # Crew Banner
            draw_centered_text(draw, 40, "★ THE 7 HEROES OF TASSIN LA DEMI-LUNE ★", font_large,
                               fill=(255, 215, 0), border=(0, 0, 0), bw=4)
            draw_centered_text(draw, 78, "Clement • Clara • Arthur • Lea • Natan • Raphael • Luca", font_small,
                               fill=(255, 255, 255), border=(20, 20, 50), bw=3)

            # Flash out at end of scene
            if f >= 284:
                alpha = int(((f - 283) / 4.0) * 255)
                flash = Image.new("RGBA", (W, H), (255, 255, 220, alpha))
                frame_img.paste(flash, (0, 0), flash)

        # --------------------------------------------------------
        # SCENE 5: KAWAII HYPER-BEAM CLIMAX (12.0s - 15.0s | frames 288 - 359)
        # --------------------------------------------------------
        else:
            prog = (f - 288) / 71.0
            # Energy struggle pulse zoom
            vibe_zoom = 1.05 + math.sin(prog * math.pi * 8) * 0.04
            frame_img = apply_ken_burns(img_climax, z_start=vibe_zoom, z_end=vibe_zoom + 0.02,
                                        pan_x_start=random.randint(-3, 3), pan_x_end=random.randint(-3, 3),
                                        pan_y_start=random.randint(-3, 3), pan_y_end=random.randint(-3, 3),
                                        progress=prog)
            draw = ImageDraw.Draw(frame_img)

            # Expanding energy shockwaves
            ring_r = int((prog * 500) % 250)
            draw.ellipse([W//2 - ring_r, H//2 - ring_r, W//2 + ring_r, H//2 + ring_r],
                         outline=(255, 215, 0), width=4)

            # Climax Title Card (Frame 305 - 345)
            if 305 <= f <= 350:
                card_scale = min(1.0, (f - 305) / 10.0)
                pulse_y = math.sin((f - 305) * 0.2) * 4
                draw_centered_text(draw, int(H//2 - 60 + pulse_y), "🍟 NATALIE'S ANNULAIRE 🍟", font_huge,
                                   fill=(255, 215, 0), border=(192, 57, 43), bw=5)
                draw_centered_text(draw, int(H//2 + 5 + pulse_y), "LE BRAQUAGE TROLL ULTIME • MC'DO TASSIN", font_mid,
                                   fill=(255, 255, 255), border=(0, 0, 0), bw=3)
                draw_centered_text(draw, int(H//2 + 45 + pulse_y), "【 START THE HEIST NOW 】", font_small,
                                   fill=(129, 236, 236), border=(0, 0, 0), bw=2)

            # Final fade to black at last 8 frames
            if f >= 352:
                fade_alpha = int(((f - 351) / 8.0) * 255)
                fade = Image.new("RGBA", (W, H), (0, 0, 0, fade_alpha))
                frame_img.paste(fade, (0, 0), fade)

        # Write frame bytes to FFmpeg stdin
        proc.stdin.write(frame_img.tobytes())

        if f % 48 == 0:
            print(f"Rendered frame {f}/{TOTAL_FRAMES} ({(f/FPS):.1f}s)...")

    proc.stdin.close()
    proc.wait()
    print(f"✅ Detailed Anime Intro Video generated successfully: {OUTPUT_PATH}")

if __name__ == "__main__":
    main()
